_STDLIB_TAIL = '''

# --------------------------------------------------------------------------- #
# Standalone server (no framework): run it next to your app as a sidecar —
#   python ava/surface.py            # serves http://127.0.0.1:__PORT__
# --------------------------------------------------------------------------- #
import json
import os
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

PORT = int(os.environ.get("__ENV_PORT__", "__PORT__"))


class _Handler(BaseHTTPRequestHandler):
    def _send(self, code: int, payload: dict) -> None:
        body = json.dumps(payload).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        path = self.path.split("?")[0]
        if path == "/health":
            return self._send(200, {"ok": True})
        if path == "/.well-known/ava.json":
            return self._send(200, {**WELL_KNOWN, "health": "/health"})
        if path == "/tools":
            return self._send(200, _listing())
        self._send(404, {"error": "not found"})

    def do_POST(self):
        if self.path.split("?")[0] != "/call":
            return self._send(404, {"error": "not found"})
        try:
            n = int(self.headers.get("Content-Length") or 0)
            body = json.loads(self.rfile.read(n) or b"{}")
        except Exception:  # noqa: BLE001
            return self._send(400, {"error": "invalid json"})
        data, status = _dispatch(str(body.get("name") or ""), body.get("arguments") or {})
        self._send(status, data)

    def log_message(self, *a):  # quiet
        pass


if __name__ == "__main__":
    print(f"[__ID__ agent surface] http://127.0.0.1:{PORT}")
    ThreadingHTTPServer(("127.0.0.1", PORT), _Handler).serve_forever()
'''

