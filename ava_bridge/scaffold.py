_FASTAPI_TAIL = '''

# --------------------------------------------------------------------------- #
# FastAPI wiring — in your app:  from ava.surface import register; register(app)
# Register BEFORE any catch-all static mount (app.mount("/")) or the routes
# will be shadowed.
# --------------------------------------------------------------------------- #
# Module-level imports on purpose: `from __future__ import annotations` makes
# annotations strings, and FastAPI resolves them in module globals — a
# closure-local Request/model lands in query params instead of the body.
from fastapi import Request  # noqa: E402
from fastapi.responses import JSONResponse  # noqa: E402
from starlette.concurrency import run_in_threadpool  # noqa: E402


def register(app) -> None:
    @app.get("/.well-known/ava.json")
    def well_known():
        return WELL_KNOWN

    @app.get("/tools")
    def tools():
        return _listing()

    @app.post("/call")
    async def call(request: Request):
        try:
            body = await request.json()
        except Exception:  # noqa: BLE001
            return JSONResponse({"error": "invalid json"}, status_code=400)
        body = body if isinstance(body, dict) else {}
        # Threadpool on purpose: handlers are sync and often do blocking IO —
        # including HTTP back to THIS app. Dispatching on the event loop would
        # starve it and deadlock any self-call.
        data, status = await run_in_threadpool(
            _dispatch, str(body.get("name") or ""), body.get("arguments") or {})
        return JSONResponse(data, status_code=status)
'''

